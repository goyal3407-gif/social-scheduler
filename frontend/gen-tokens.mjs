// gen-tokens.mjs — Round 2 (D-4): public/tokens.css is GENERATED
// from the SPA token blocks in src/index.css, never hand-synced.
// The static pages (privacy, terms, contact, app-start, app-return)
// link tokens.css because they are plain HTML; this script keeps
// their token values identical to the app's by construction. It runs
// in the build before vite (same pattern as gen-icons.mjs) and fails
// the build if a needed token disappears from index.css.
// The static pages' base styles (body/h1/h2/a/.muted/.back) live in
// the template below — they are not part of the SPA stylesheet.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const css = readFileSync(join(here, 'src', 'index.css'), 'utf8')

// The token subset the static pages use (in emit order).
const SUBSET = ['--bg', '--surface', '--ink', '--ink-2', '--muted', '--line', '--gold-text', '--brand-text', '--red-text']

function block(selectorRe) {
  const m = css.match(selectorRe)
  if (!m) throw new Error(`gen-tokens: block not found: ${selectorRe}`)
  return m[1]
}
function tokens(blockText) {
  const out = {}
  for (const m of blockText.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/gi)) out[m[1]] = m[2].trim()
  return out
}
const light = tokens(block(/:root\{([^}]+)\}/))
const dark = tokens(block(/\[data-theme="dark"\]\{([^}]+)\}/))
for (const name of SUBSET) {
  if (!light[name] || !dark[name]) throw new Error(`gen-tokens: ${name} missing from a token block in src/index.css`)
}
const line = (t) => SUBSET.map((n) => `${n}: ${t[n]};`).join(' ')
const out = `/* GENERATED by gen-tokens.mjs from src/index.css — do not edit by
   hand (Round 2, D-4). KiluaAI design tokens for the static pages
   (privacy, terms, contact, app-start, app-return): the same values
   as the app's token layer, served as a plain file because these
   pages are static HTML. Dark values follow the OS setting here —
   the static pages have no in-app theme toggle. */
:root {
  ${line(light)}
}
@media (prefers-color-scheme: dark) {
  :root {
    ${line(dark)}
  }
}
body {
  font-family: system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;
  line-height: 1.6; background: var(--bg); color: var(--ink);
  max-width: 760px; margin: 0 auto; padding: 32px 20px 64px;
}
h1 { font-size: 1.7rem; line-height: 1.25; }
h2 { font-size: 1.15rem; margin-top: 2rem; }
a { color: var(--brand-text); }
.muted { color: var(--muted); }
.back { margin: 0 0 20px; }
.back a { color: var(--gold-text); font-weight: 600; text-decoration: none; }
.back a:hover { text-decoration: underline; }
`
writeFileSync(join(here, 'public', 'tokens.css'), out)
console.log(`[gen-tokens] wrote public/tokens.css (${SUBSET.length} tokens x light/dark, from src/index.css)`)
