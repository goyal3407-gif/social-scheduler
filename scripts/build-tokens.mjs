// build-tokens.mjs — Round 3 (B1): the REAL token generator.
// public/tokens.css is GENERATED from the SPA token blocks in
// frontend/src/index.css, never hand-synced. The static pages
// (privacy, terms, contact, app-start, app-return) link tokens.css
// because they are plain HTML; this script keeps their token values
// identical to the app's by construction. It emits the FULL token
// set (every token, both themes): the dark section is the light set
// overridden by the dark token block, so tokens the dark block does
// not redefine (radius, type, fonts…) are still present.
// frontend/gen-tokens.mjs is a thin shim delegating here, so the
// existing build wiring (`node gen-tokens.mjs`) keeps working.
// The static pages' base styles (body/h1/h2/a/.muted/.back) live in
// the template below — they are not part of the SPA stylesheet.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const frontendDir = join(here, '..', 'frontend')
const css = readFileSync(join(frontendDir, 'src', 'index.css'), 'utf8')

function block(selectorRe) {
  const m = css.match(selectorRe)
  if (!m) throw new Error(`build-tokens: block not found: ${selectorRe}`)
  return m[1]
}
function tokens(blockText) {
  const out = {}
  for (const m of blockText.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/gi)) out[m[1]] = m[2].trim()
  return out
}
const light = tokens(block(/:root\{([^}]+)\}/))
const darkOwn = tokens(block(/\[data-theme="dark"\]\{([^}]+)\}/))
// Tokens the static pages have always relied on must never vanish.
const REQUIRED = ['--bg', '--surface', '--ink', '--ink-2', '--muted', '--line', '--gold-text', '--brand-text', '--red-text']
for (const name of REQUIRED) {
  if (!light[name] || !darkOwn[name]) throw new Error(`build-tokens: ${name} missing from a token block in src/index.css`)
}
const dark = { ...light, ...darkOwn }
const lines = (t) => Object.entries(t).map(([n, v]) => `  ${n}: ${v};`).join('\n')
const out = `/* GENERATED by gen-tokens.mjs — do not edit by hand. The real
   generator is scripts/build-tokens.mjs (frontend/gen-tokens.mjs is
   a thin shim that delegates to it). KiluaAI design tokens for the
   static pages (privacy, terms, contact, app-start, app-return):
   the same values as the app's token layer, served as a plain file
   because these pages are static HTML. Dark values follow the OS
   setting here — the static pages have no in-app theme toggle. */
:root {
${lines(light)}
}
[data-theme="dark"] {
${lines(dark)}
}
@media (prefers-color-scheme: dark) {
  :root {
${lines(dark)}
  }
}
body {
  font-family: 'Inter', system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;
  line-height: 1.6; background: var(--bg); color: var(--ink);
  max-width: 760px; margin: 0 auto; padding: 32px 20px 64px;
}
h1 { font-size: 1.7rem; line-height: 1.25; }
h2 { font-size: 1.15rem; margin-top: 2rem; }
a { color: var(--brand-text); }
.muted { color: var(--muted); }
.back { margin: 0 0 20px; }
.back a { color: var(--brand-text); font-weight: 600; text-decoration: none; }
.back a:hover { text-decoration: underline; }
`
writeFileSync(join(frontendDir, 'public', 'tokens.css'), out)
console.log(`[build-tokens] wrote public/tokens.css (${Object.keys(light).length} light tokens, ${Object.keys(dark).length} dark tokens, from src/index.css)`)
